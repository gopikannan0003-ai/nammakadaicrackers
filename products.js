/* =========================
   URL CATEGORY
========================= */

function loadCategoryFromURL() {

    const params =
        new URLSearchParams(
            window.location.search
        );


    const category =
        params.get("category");


    if (category) {

        const option =
            [...categoryFilter.options]
                .find(
                    option =>
                        option.value === category
                );


        if (option) {

            categoryFilter.value =
                category;

        }

    }

}



